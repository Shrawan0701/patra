export function createCustomProject(category: CategoryMeta['id'] = 'wedding', roomCount = 1): ProjectConfig {
  const catTemplates = TEMPLATES.filter((t) => t.category === category);
  const seed = catTemplates[0] ?? TEMPLATES[0];
  const baseRoom = seed.project.rooms[0];
  const count = Math.min(4, Math.max(1, roomCount));
  const corners: 2 | 3 | 4 = count <= 2 ? (seed.project.cornersCount ?? 4) : (Math.min(4, count) as 3 | 4);

  const rooms: RoomConfig[] = Array.from({ length: count }, (_, idx) => ({
    ...baseRoom,
    id: `custom_r${idx + 1}`,
    label: idx === 0 ? baseRoom.label : `Room ${idx + 1}`,
    sideProps: [...baseRoom.sideProps],
    signage: {
      ...baseRoom.signage,
      eventTitle: idx === 0 ? baseRoom.signage.eventTitle : `Ceremony ${idx + 1}`,
    },
  }));

  return {
    title: `My Custom ${seed.project.category.replace('_', ' ')} Card`,
    category,
    aspectRatio: '9:16',
    musicId: seed.project.musicId,
    structure: seed.project.structure ?? 'carousel_gable',
    cornersCount: corners,
    rooms,
  };
}

